/**
 * Clipboard history rules (pure; no Electron). What counts as worth keeping, how items are
 * de-duplicated, and when they expire. The main process watches the system clipboard and applies
 * these; nothing here touches the clipboard or the disk.
 */
export type ClipKind = 'text' | 'link' | 'image';

export const CLIP_LIMITS = {
  /** Items older than this are removed (48 hours). */
  maxAgeMs: 48 * 3_600_000,
  maxItems: 100,
  maxTextChars: 100_000,
  maxImageBytes: 5_000_000,
  /** All stored images together; the oldest go first. */
  maxImageTotalBytes: 50_000_000,
} as const;

/** macOS marks secrets (password managers) with these pasteboard types; they're never stored. */
export const CONCEALED_TYPES = [
  'org.nspasteboard.ConcealedType',
  'org.nspasteboard.TransientType',
  'org.nspasteboard.AutoGeneratedType',
  'com.agilebits.onepassword',
];

export function isConcealed(formats: readonly string[]): boolean {
  return formats.some((f) => CONCEALED_TYPES.includes(f));
}

/** A lone http(s) address (no spaces or other text) is a link. */
export function isLink(text: string): boolean {
  const t = text.trim();
  if (/\s/.test(t)) return false;
  try {
    const u = new URL(t);
    return u.protocol === 'http:' || u.protocol === 'https:';
  } catch {
    return false;
  }
}

export type ClipInput =
  { kind: 'text'; text: string } | { kind: 'image'; bytes: number; hash: string };

/** What to store for a clipboard reading, or null (empty, blank, too big, a secret). */
export function classify(
  formats: readonly string[],
  text: string,
  image: { bytes: number; hash: string } | null,
): { kind: ClipKind; text: string; key: string } | null {
  if (isConcealed(formats)) return null;
  const t = text.trim();
  if (t) {
    if (t.length > CLIP_LIMITS.maxTextChars) return null;
    return { kind: isLink(t) ? 'link' : 'text', text: t, key: `t:${t}` };
  }
  if (image && image.bytes > 0 && image.bytes <= CLIP_LIMITS.maxImageBytes) {
    return { kind: 'image', text: '', key: `i:${image.hash}` };
  }
  return null;
}

/** Ids to delete: expired items, then the oldest beyond the count and image-size budgets.
 *  `items` is newest first. */
export function pruneIds(
  items: readonly { id: string; createdAt: number; imageBytes: number }[],
  now: number,
): string[] {
  const drop = new Set<string>();
  let kept = 0;
  let imageTotal = 0;
  for (const item of items) {
    const expired = now - item.createdAt > CLIP_LIMITS.maxAgeMs;
    if (expired || kept >= CLIP_LIMITS.maxItems) {
      drop.add(item.id);
      continue;
    }
    if (item.imageBytes > 0 && imageTotal + item.imageBytes > CLIP_LIMITS.maxImageTotalBytes) {
      drop.add(item.id);
      continue;
    }
    kept++;
    imageTotal += item.imageBytes;
  }
  return [...drop];
}

/** "Clipboard" row title: the first line, shortened. */
export function clipPreview(text: string, max = 120): string {
  const line = text.trim().split('\n', 1)[0] ?? '';
  return line.length > max ? `${line.slice(0, max - 1)}…` : line;
}
